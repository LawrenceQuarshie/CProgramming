#include <stdio.h>

int main() {
    // create integer variables
    int length = 4;
    int width = 6;
    int area;

    // calculates the area of a rectangle
    area = length * width;

    // prints the variables
    printf("Length is: %d\n", length);
    printf("Width is: %d\n", width);
    printf("Area of the rectangle is: %d\n", area);
    return 0;
}