#include <stdio.h>

int main() {
    // create a mynum variable and assign the value 15 to it
    int mynum = 15;

    // declare a myothernum variable without assigning a value to it
    int myothernum;

    // assign value of mynum to myothernum
    myothernum = mynum;

    // myothernum now has 15 as a value
    printf("%d\n", myothernum);
    return 0;
}